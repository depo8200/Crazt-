function buildSampleQuestions(subjectName: string, topics: string[]) {
  const [t1, t2, t3] = [
    topics[0] ?? 'Core Foundations',
    topics[1] ?? 'Applied Problem Solving',
    topics[2] ?? 'System Design & Analysis',
  ];
  return [
    {
      section: 'Section A — Conceptual Short Answers (Sample)',
      marks: 20,
      questions: [
        `Define the primary constraints and trade-offs involved in ${t1} within ${subjectName}.`,
        `Differentiate between standard theoretical models and practical university exam cases for ${t2}.`,
        `State two real-world failure scenarios related to ${t3} and outline how to mitigate them.`,
        `Explain the key notation and boundary conditions frequently tested in ${t1}.`,
      ],
    },
    {
      section: 'Section B — Analytical & Derivation Problems (Sample)',
      marks: 30,
      questions: [
        `Walk through a step-by-step derivation or trace for a representative problem in ${t2}, stating every assumption clearly.`,
        `Compare two competing approaches used in ${t3} across efficiency, scalability, and edge-case accuracy.`,
        `Given a multi-stage scenario combining ${t1} and ${t2}, evaluate the intermediate states and justify the final output.`,
      ],
    },
    {
      section: 'Section C — Long-Form Design & Case Study (Sample)',
      marks: 20,
      questions: [
        `Design a complete end-to-end solution integrating ${t1}, ${t2}, and ${t3}. Include labeled diagrams and complexity or performance justification.`,
        `Critically analyze a high-load case study in ${subjectName} and propose three measurable optimizations.`,
      ],
    },
  ];
}

